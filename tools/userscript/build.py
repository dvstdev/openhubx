#!/usr/bin/env python3
"""Builds the two OpenHubX QR userscripts.

Each output is one self-contained .user.js: a Tampermonkey header, the QR encoder
copied from tools/qr-generator/index.html (so there is one vendored copy, MIT
license header kept), the shared core, and the script's entry code. No @require,
so no remote code runs on the GitHub token page.

Run:  python3 tools/userscript/build.py
"""
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
GENERATOR = HERE.parent / "qr-generator" / "index.html"
VERSION = "1.0.0"

HEADERS = {
    "openhubx-github-tokens.user.js": f"""// ==UserScript==
// @name         OpenHubX: QR for GitHub tokens
// @namespace    https://github.com/dvstdev/openhubx
// @version      {VERSION}
// @description  Adds a QR button next to each GitHub token on your token pages. Click it to show an OpenHubX login QR. Offline.
// @match        https://github.com/settings/*
// @grant        GM_registerMenuCommand
// @run-at       document-idle
// @noframes
// ==/UserScript==
""",
    "openhubx-qr-selection.user.js": f"""// ==UserScript==
// @name         OpenHubX: QR from selected text
// @namespace    https://github.com/dvstdev/openhubx
// @version      {VERSION}
// @description  Right-click > Tampermonkey > this script: QR code for the selected text. GitHub tokens become an OpenHubX login QR. Offline.
// @match        *://*/*
// @grant        GM_info
// @run-at       context-menu
// ==/UserScript==
""",
}

ENTRIES = {
    "openhubx-github-tokens.user.js": "github-tokens.entry.js",
    "openhubx-qr-selection.user.js": "selection.entry.js",
}


def vendored_qr_lib() -> str:
    """Returns the vendored qrcode-generator block (with its license) from the offline page."""
    html = GENERATOR.read_text(encoding="utf-8")
    m = re.search(r"// ---- Vendored QR encoder.*?(?=</script>)", html, re.S)
    if not m:
        raise SystemExit(f"QR encoder block not found in {GENERATOR}")
    return m.group(0)


def main() -> None:
    """Writes each .user.js next to this script, wrapped in one function scope."""
    lib = vendored_qr_lib()
    core = (HERE / "qr-core.js").read_text(encoding="utf-8")
    for out, header in HEADERS.items():
        entry = (HERE / ENTRIES[out]).read_text(encoding="utf-8")
        body = "\n".join([
            header,
            "// GENERATED by tools/userscript/build.py - edit qr-core.js / *.entry.js instead.",
            "(function () {",
            lib,
            core,
            entry,
            "})();",
            "",
        ])
        (HERE / out).write_text(body, encoding="utf-8")
        print(f"wrote {out} ({len(body):,} bytes)")


if __name__ == "__main__":
    main()
